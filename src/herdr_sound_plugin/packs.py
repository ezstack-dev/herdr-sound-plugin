def labels() -> list[str]:
    """全部包名（按字母序）。"""
    return sorted(PACKS)


def notes_of(pack: str, kind: str) -> Notes:
    """取某个包某个用途的谱子；包名或用途不存在时抛 KeyError。"""
    return PACKS[pack][kind]
